"""Exploration animation of one V4 closed-loop episode (CPU): GIF of the planning loop, built only from measured data
(anim_replay.py + anim_gt.py outputs).

Each decision step is drawn in two phases for the first steps and as one frame afterwards:
  (1) imagine  top view: GT surface (grey = not yet seen, teal = already covered), the path so far, the current camera and
               the 5 best-scoring candidate cameras (A = highest predicted new surface); right: for each candidate the
               K = 4 imagined depth maps (the part the model generates = rays still UNKNOWN; known rays are faded)
  (2) choose   the chosen candidate is highlighted, its imagined surface is drawn on the top view (orange), the camera
               moves, the depth it actually sees is shown next to its 4 imagined maps, coverage updates.
Usage: python anim_make.py --name out_colosseum_s2 [--gif PATH]"""
import argparse
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from matplotlib.colors import ListedColormap  # noqa: E402
from PIL import Image  # noqa: E402

R = "/bsuscratch/jiahuizhang/projects/occupancy/seen2scene"
V = os.path.join(R, "work_dirs", "exp6_v4", "weekly_report_anim")
OUTD = os.path.join(R, "experiments", "exp6_v4", "weekly_report", "animations")
W4 = os.path.join(R, "work_dirs", "exp6_v4", "eval", "closed_loop")
SURF, INK, INK2, MUTED, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#8a8984", "#e6e5e1"
BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"
LET = "ABCDE"
ENC = "libx264"
plt.rcParams.update({"figure.facecolor": SURF, "axes.facecolor": SURF, "savefig.facecolor": SURF, "axes.edgecolor": GRID, "axes.labelcolor": INK2,
                     "xtick.color": INK2, "ytick.color": INK2, "text.color": INK, "font.size": 9, "font.family": "DejaVu Sans"})


def load(name):
    z = np.load(os.path.join(V, f"{name}.npz"))
    meta = json.loads(str(z["meta"]))
    gname = ("gt_out_" if meta["domain"] == "outdoor" else "gt_in_") + name.split("_", 1)[1]
    g = np.load(os.path.join(V, f"{gname}.npz"))
    return {k: z[k] for k in z.files}, meta, {k: g[k] for k in g.files}


def observed_depth(meta, t):
    """Depth the executed camera actually measured at step t (64 x 114, runtime units), from the service record."""
    if meta["domain"] == "outdoor":
        s, k = meta["scene"], meta["start"]
        p = os.path.join(W4, "outdoor", "V4", "V2M", "svc", meta["tag"], f"svc_{s}_s{k}_t{t}.npz")
    else:
        p = os.path.join(W4, "indoor", "V4", "V2M", meta["tag"], "svc", f"svc_t{t}.npz")
    if not os.path.exists(p):
        return None
    z = np.load(p)
    d = np.where(z["mask"] & (z["zbuf"] < 70.0), np.clip(z["zbuf"], 0.5, 750.0), np.nan)
    return d[1::4, 1::4][:64, :114]


def depth_rgb(d, unk, vmax, cm):
    """RGB thumbnail: rays still UNKNOWN in the current map (generated by the model) in colour, known rays in grey."""
    x = np.clip(np.nan_to_num(d / vmax, nan=0.0), 0, 1)
    col = cm(x)[..., :3]
    grey = plt.get_cmap("Greys")(0.12 + 0.45 * x)[..., :3]
    rgb = np.where(unk[..., None], col, grey)
    rgb[~np.isfinite(d)] = [0.99, 0.99, 0.985]
    return rgb


def frames_schedule(T, indoor):
    out = []
    for t in range(T):
        if t < 6:
            out += [(t, "imagine", 1.6), (t, "choose", 1.6)]
        elif t < 30:
            out.append((t, "choose", 0.45))
        elif t % (3 if indoor else 2) == 0 or t == T - 1:
            out.append((t, "choose", 0.3))
    out.append((T - 1, "final", 3.5))
    return out


def make(name, gif=None, mp4=False):
    z, meta, g = load(name)
    indoor = meta["domain"] == "indoor"
    sc, unit = (1 / 7.0, "m") if indoor else (1.0, "scene units")
    T = len(z["t"])
    curve = np.asarray(g["curve"])
    P = g["pts"].astype(np.float64)
    first = g["first"].astype(int)
    rng = np.random.default_rng(0)
    sel = rng.choice(len(P), min(len(P), 30000), replace=False)
    if indoor:
        sel = sel[g["counted"][sel]]
    XY = np.stack([P[sel, 0], -P[sel, 2]], 1) * sc
    F = first[sel]
    pad = 0.04 * (XY.max(0) - XY.min(0)).max()
    lo, hi = XY.min(0) - pad, XY.max(0) + pad
    L = 0.9 if indoor else 0.07 * (hi - lo).max()
    dep = z["top_depth"].astype(np.float32) * sc
    vmax = float(np.nanpercentile(dep[np.isfinite(dep)], 98))
    cm = plt.get_cmap("viridis").copy(); cm.set_bad(SURF)
    sched = frames_schedule(T, indoor)
    title = f"{'Indoor (MP3D, V4 zero-shot)' if indoor else 'Outdoor (Macarons++)'} — {meta['scene'].replace('_', ' ')}, start {meta['start']}"
    imgs, durs = [], []
    fig = plt.figure(figsize=(14.2, 7.4), dpi=92)
    for (t, phase, dur) in sched:
        fig.clf()
        gs = fig.add_gridspec(2, 2, width_ratios=[1.05, 1.0], height_ratios=[3.1, 1.0], left=0.04, right=0.985, top=0.86, bottom=0.07, wspace=0.12, hspace=0.32)
        shown_t = t + 1 if phase in ("choose", "final") and t + 1 < len(curve) else t
        cov = curve[min(shown_t, len(curve) - 1)]
        pick, top = int(z["pick"][t]), [int(x) for x in z["top"][t] if x >= 0]
        qpick = top.index(pick)
        if phase == "imagine":
            sub = f"step {t}:  ① the planner imagines what each of its {len(top)} best candidate cameras would see (K = 4 possible futures each)"
        elif phase == "choose":
            sub = f"step {t}:  ② it picks {LET[qpick]} (most predicted NEW surface) and moves there; right column = what that camera really saw"
        else:
            sub = f"end of episode: {T} moves, final coverage {curve[-1] * 100:.1f} %"
        fig.text(0.012, 0.955, title, fontsize=13, fontweight="bold")
        fig.text(0.012, 0.915, sub, fontsize=10.5, color=INK2)
        fig.text(0.988, 0.955, f"coverage {cov * 100:.1f} %", fontsize=13, fontweight="bold", ha="right", color=AQUA)
        # ---------------- top view
        ax = fig.add_subplot(gs[:, 0])
        cov_m = (F >= 0) & (F <= shown_t)
        ax.scatter(XY[~cov_m, 0], XY[~cov_m, 1], s=0.6, color="#cfcec9", lw=0, rasterized=True)
        ax.scatter(XY[cov_m, 0], XY[cov_m, 1], s=0.8, color=AQUA, lw=0, rasterized=True)
        path_t = shown_t if phase != "imagine" else t
        C = z["cam_center"][: path_t + 1].astype(np.float64)
        if phase != "imagine" and t + 1 < T:
            C = np.concatenate([z["cam_center"][: t + 1], z["cand_center"][t, pick][None]]).astype(np.float64)
        Cx = np.stack([C[:, 0], -C[:, 2]], 1) * sc
        ax.plot(Cx[:, 0], Cx[:, 1], "-", color=INK2, lw=1.4, alpha=0.8, zorder=3)
        ax.plot(Cx[:-1, 0], Cx[:-1, 1], "o", color=INK2, ms=2.5, zorder=3)
        cur = np.array([z["cam_center"][t, 0], -z["cam_center"][t, 2]]) * sc
        cf = np.array([z["cam_fwd"][t, 0], -z["cam_fwd"][t, 2]])
        if phase != "final":
            placed = []
            for q, j in enumerate(top):
                o = np.array([z["cand_center"][t, j, 0], -z["cand_center"][t, j, 2]]) * sc
                f = np.array([z["cand_fwd"][t, j, 0], -z["cand_fwd"][t, j, 2]])
                tip = o + f * L
                chosen = phase == "choose" and j == pick
                col = BLUE if chosen else plt.get_cmap("Blues")(0.85 - 0.12 * q)
                ax.annotate("", xy=tip, xytext=o, arrowprops={"arrowstyle": "-|>", "color": col, "lw": 3.0 if chosen else 1.6, "mutation_scale": 13, "alpha": 1 if (chosen or phase == "imagine") else 0.45}, zorder=5)
                lab = tip + f * L * 0.35
                for _ in range(10):
                    if all(np.linalg.norm(lab - p_) > 0.3 * L for p_ in placed):
                        break
                    lab = lab + np.array([-f[1], f[0]]) * 0.3 * L
                placed.append(lab)
                ax.text(*lab, LET[q], ha="center", va="center", fontsize=10, fontweight="bold", color=BLUE if chosen else INK, zorder=7,
                        bbox={"boxstyle": "round,pad=0.12", "fc": SURF, "ec": BLUE if chosen else "none", "alpha": 0.85})
            if phase == "choose":
                pp = z["pick_pts"][t]
                pp = pp[np.isfinite(pp[:, 0])]
                ax.scatter(pp[:, 0] * sc, -pp[:, 2] * sc, s=2.0, color=ORANGE, alpha=0.5, lw=0, zorder=4, rasterized=True)
        ax.plot(*cur, marker="s", ms=8, color=INK, zorder=8)
        ax.annotate("", xy=cur + cf * L * 0.8, xytext=cur, arrowprops={"arrowstyle": "-|>", "color": INK, "lw": 1.6, "ls": "--"}, zorder=8)
        ax.set_xlim(lo[0], hi[0]); ax.set_ylim(lo[1], hi[1]); ax.set_aspect("equal")
        ax.set_xlabel(f"x ({unit})"); ax.set_ylabel(f"y ({unit})")
        ax.set_title("top view (GT surface points shown for reference only)", loc="left", fontsize=9.5, color=INK2)
        hs = [plt.Line2D([], [], marker="o", ls="", color="#cfcec9", ms=5), plt.Line2D([], [], marker="o", ls="", color=AQUA, ms=5),
              plt.Line2D([], [], color=INK2, lw=1.4), plt.Line2D([], [], marker="s", ls="", color=INK, ms=6),
              plt.Line2D([], [], color=plt.get_cmap("Blues")(0.8), lw=2), plt.Line2D([], [], marker="o", ls="", color=ORANGE, ms=5)]
        ax.legend(hs, ["surface not yet seen", "surface already covered", "path", "current camera", "candidate cameras (A = best)", "imagined surface of the chosen camera"],
                  loc="lower left", fontsize=7.6, frameon=True, framealpha=0.9, edgecolor=GRID)
        # ---------------- imagined depth grid
        gsr = gs[0, 1].subgridspec(len(top), 6, width_ratios=[0.62, 1, 1, 1, 1, 1], wspace=0.05, hspace=0.12)
        sc_all = z["scores"][t]
        smax = np.nanmax(sc_all) if np.isfinite(sc_all).any() else 1.0
        obs = observed_depth(meta, t + 1) if phase == "choose" else None
        for q, j in enumerate(top):
            chosen = phase == "choose" and j == pick
            axl = fig.add_subplot(gsr[q, 0]); axl.set_xlim(0, 1); axl.set_ylim(0, 1); axl.axis("off")
            axl.text(0.02, 0.72, LET[q], fontsize=12, fontweight="bold", color=BLUE if chosen else INK, va="center")
            axl.barh(0.3, sc_all[j] / smax * 0.95, height=0.22, left=0.02, color=BLUE if chosen else "#9cc3ee")
            axl.text(0.24, 0.72, f"{sc_all[j]:.0f}", fontsize=8, va="center", color=INK2)
            unk = z["top_cls"][t, q] == 0
            for kk in range(4):
                a_ = fig.add_subplot(gsr[q, 1 + kk])
                a_.imshow(depth_rgb(dep[t, q, kk], unk, vmax, cm), interpolation="nearest")
                a_.set_xticks([]); a_.set_yticks([])
                for sp in a_.spines.values():
                    sp.set_color(BLUE if chosen else GRID); sp.set_linewidth(2.2 if chosen else 0.8)
                if q == 0:
                    a_.set_title(f"imagined {kk + 1}", fontsize=8.5)
            a_ = fig.add_subplot(gsr[q, 5]); a_.set_xticks([]); a_.set_yticks([])
            for sp in a_.spines.values():
                sp.set_color(ORANGE if chosen else SURF); sp.set_linewidth(2.2)
            if q == 0:
                a_.set_title("really seen", fontsize=8.5, color=ORANGE)
            if chosen and obs is not None:
                a_.imshow(depth_rgb(obs * sc, unk, vmax, cm), interpolation="nearest")          # same unknown mask as the imagined maps
        fig.text(0.535, 0.885, "cand. + score", fontsize=8.5, color=INK2)
        fig.text(0.535, 0.285, f"colour = depth on rays unknown before the move (imagined = generated, really seen = measured), 0-{vmax:.0f} {unit}\n"
                 "grey = part of the view the map already knew  ·  score = predicted new surface (DistP1), the planner picks the highest", fontsize=7.8, color=INK2, linespacing=1.4)
        # ---------------- coverage curve
        axc = fig.add_subplot(gs[1, 1])
        x = np.arange(len(curve))
        axc.plot(x, curve * 100, color=GRID, lw=1.5)
        axc.plot(x[: shown_t + 1], curve[: shown_t + 1] * 100, color=AQUA, lw=2.2)
        axc.plot(shown_t, curve[shown_t] * 100, "o", color=AQUA, ms=6)
        axc.set_xlim(0, len(curve) - 1); axc.set_ylim(0, max(curve) * 100 * 1.08)
        axc.set_xlabel("move"); axc.set_ylabel("coverage %")
        axc.grid(color=GRID, lw=0.6); axc.set_axisbelow(True)
        for sp in ("top", "right"):
            axc.spines[sp].set_visible(False)
        fig.canvas.draw()
        imgs.append(np.asarray(fig.canvas.buffer_rgba())[..., :3].copy())
        durs.append(int(dur * 1000))
    plt.close(fig)
    os.makedirs(OUTD, exist_ok=True)
    gif = gif or os.path.join(OUTD, f"explore_{name}.gif")
    idx = np.linspace(0, len(imgs) - 1, min(10, len(imgs))).astype(int)                     # one palette for all frames
    pal = Image.fromarray(np.concatenate([imgs[i][::2, ::2] for i in idx], 0)).quantize(colors=200, method=Image.Quantize.MEDIANCUT)
    frames = [Image.fromarray(x).quantize(palette=pal, dither=Image.Dither.NONE) for x in imgs]
    frames[0].save(gif, save_all=True, append_images=frames[1:], duration=durs, loop=0, optimize=True, disposal=1)
    print("saved", gif, len(frames), "frames", f"{os.path.getsize(gif) / 2 ** 20:.1f} MB")
    if mp4:
        import shutil
        import subprocess
        import tempfile
        ff = "/bsuscratch/jiahuizhang/envs/seen2scene/bin/ffmpeg"
        td = tempfile.mkdtemp(dir=V)
        lines = []
        for i, (x, d) in enumerate(zip(imgs, durs)):
            fp = os.path.join(td, f"f{i:04d}.png")
            Image.fromarray(x[: x.shape[0] // 2 * 2, : x.shape[1] // 2 * 2]).save(fp)
            lines += [f"file '{fp}'", f"duration {d / 1000:.3f}"]
        lines.append(f"file '{fp}'")
        open(os.path.join(td, "list.txt"), "w").write("\n".join(lines) + "\n")
        out_mp4 = gif[:-4] + ".mp4"
        subprocess.run([ff, "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", os.path.join(td, "list.txt"), "-vsync", "vfr", "-pix_fmt", "yuv420p",
                        "-c:v", ENC, "-crf", "23", out_mp4] if ENC == "libx264" else
                       [ff, "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", os.path.join(td, "list.txt"), "-vsync", "vfr", "-pix_fmt", "yuv420p", "-c:v", ENC, "-q:v", "4", out_mp4], check=True)
        shutil.rmtree(td, ignore_errors=True)
        print("saved", out_mp4, f"{os.path.getsize(out_mp4) / 2 ** 20:.1f} MB")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--gif", default=None)
    ap.add_argument("--mp4", action="store_true")
    a = ap.parse_args()
    make(a.name, a.gif, a.mp4)
