"""Table 5 v3 (2026-11-16, user request): coverage only (no AUC) + predictive-distribution metrics, Unseen-6. Same data, rows, alignment
and statistics as v2 (make_table5_v2.py: single sample = mean over noise maps 0-3; paired scene bootstrap for coverage, trajectory-cluster
bootstrap for CRPS / energy score on the unseen-scene fixed states; '†' = difference to Seen2Map with 95 % CI excluding 0; bold = best).
  table5_v3       CRPS, Energy score, Cov@80, Cov@100. The caption states that early coverage (Cov@20 / Cov@50) is comparable and n.s.
                  and points to the full time course -- the table is about the claim (distribution accuracy + completeness).
  table5_v3_full  CRPS, Energy score, Cov@20, Cov@50, Cov@80, Cov@100 (full time course; supplementary / comparison).
Cross-check: every value equals table5_v2_metric_panel.csv. Outputs fig/table5/table5_v3{,_full}.{csv,md,tex,pdf,png}."""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cvpr_lib as L  # noqa: E402
import make_table5_v2 as T  # noqa: E402

RD = T.RD
OUT = T.OUT


def build(tag, cols, cl, fx_u, cap_extra):
    val, mark = {}, {}
    for a, _ in T.ROWS:
        for c, _, src, nd in cols:
            if src == "fx":
                v, d, lo, hi = fx_u[c][a]
            else:
                v = float(cl[c][a].mean())
                d, lo, hi = T.paired_scene(cl[c][a], cl[c]["G4"]) if a != "G4" else (0.0, 0.0, 0.0)
            val[(a, c)], mark[(a, c)] = v, a != "G4" and (lo > 0 or hi < 0)
    body, bold = [], set()
    for a, name in T.ROWS:
        body.append([name] + [f"{val[(a, c)]:.{nd}f}" + ("†" if mark[(a, c)] else "") for c, _, _, nd in cols])
    for j, (c, _, src, nd) in enumerate(cols):
        vs = [round(val[(a, c)], nd) for a, _ in T.ROWS]
        best = min(vs) if src == "fx" else max(vs)
        bold |= {(i, 1 + j) for i, v in enumerate(vs) if v == best}
    # cross-check against the v2 metric panel (record of every metric)
    panel = {(r["group"], r["metric"], r["row"]): float(r["value"]) for r in csv.DictReader(open(os.path.join(OUT, "table5_v2_metric_panel.csv")))}
    for a, name in T.ROWS:
        for c, _, src, _ in cols:
            g = "fixed states, unseen scenes (3 of Unseen-6)" if src == "fx" else "closed loop, Unseen-6"
            assert abs(panel[(g, c, name)] - val[(a, c)]) < 6e-6, (tag, a, c, panel[(g, c, name)], val[(a, c)])
    hdr = ["Prediction strategy"] + [h for _, h, _, _ in cols]
    L.write_csv(os.path.join(OUT, f"{tag}.csv"), ["Prediction strategy"] + [c for c, _, _, _ in cols], body)
    note = ("Macarons++ Unseen-6 (6 scenes no method was trained on) x 5 official starts, 100 steps, official coverage; same network family, "
            "training data, CDGR planner and protocol in every row. Single sample: mean over noise maps 0-3 (the maps of the 4-hypothesis rows). "
            "CRPS / energy score: accuracy of the predicted distribution of the future first-hit surface on held-out planning states of "
            "unseen scenes (lower is better). Cov@t: coverage after t steps. " + cap_extra + "† = difference to Seen2Map with 95% paired "
            "bootstrap CI excluding 0. Bold = best.")
    RD.table(os.path.join(OUT, tag), hdr, body, bold=bold, notes=[note], rules_after={len(T.ROWS) - 2})
    cap = ("Why multiple generative hypotheses (unseen scenes). All rows share the network family, training data, CDGR planner and "
           "evaluation protocol; only the prediction head or the use of the K = 4 generated samples changes. Keeping the hypotheses separate "
           "gives the most accurate predictive distribution of the unseen surface and the most complete coverage late in the episode. " + note)
    RD.tex(os.path.join(OUT, f"{tag}.tex"), hdr, body, bold=bold, caption=cap, label="tab:table5", rules_after={len(T.ROWS) - 2},
           colspec="l" + "c" * len(cols), notes=["generated by experiments/cvpr_results/scripts/make_table5_v3.py -- do not edit by hand (needs booktabs)"])
    md = ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    md += ["| " + " | ".join((f"**{x}**" if (i, j) in bold else x) for j, x in enumerate(r)) + " |" for i, r in enumerate(body)]
    open(os.path.join(OUT, f"{tag}.md"), "w").write("\n".join(md) + "\n\n" + note + "\n")
    print(tag)
    print("\n".join(md), "\n")


def main():
    ep = T.episodes()
    cl = T.closed_loop(ep)
    fx_u = T.fixed(lambda t: t.rsplit("_s", 1)[0].endswith(tuple("_" + s for s in T.U6)))
    assert fx_u["states"] == 211 and fx_u["trajectories"] == 16
    dist = [("CRPS", "CRPS ↓", "fx", 2), ("Energy score", "Energy score ↓", "fx", 2)]
    late = [("Cov@80", "Cov@80 ↑", "cl", 3), ("Cov@100", "Cov@100 ↑", "cl", 3)]
    early = [("Cov@20", "Cov@20 ↑", "cl", 3), ("Cov@50", "Cov@50 ↑", "cl", 3)]
    build("table5_v3", dist + late, cl, fx_u,
          "Early coverage is comparable across rows (Cov@20 / Cov@50 differences to Seen2Map not significant; full time course in the "
          "supplementary). ")
    build("table5_v3_full", dist + early + late, cl, fx_u, "")


if __name__ == "__main__":
    main()
