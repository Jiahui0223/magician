"""CVPR UAVScenes table (zero-shot, EXP7): paper-ready main table + per-tile + paired differences, saved for direct later use.

Source of every number: experiments/cvpr_results/exp7/results/uav_final_evalnorm_summary.json and
uav_final_evalnorm_UAV-final_per_tile.csv, written by exp7/scripts/uavscenes/uav_final.py --norm evaluator (2026-11-12):
  * UAV-final set: AMtown_11, AMtown_12, HKairport_00, HKairport_01 (UAV-v0) + AMvalley_01_v1, HKisland_00_v1 (UAV-v1, holes sealed);
    10 seeded starts per tile, 100 steps, frozen Macarons++ outdoor chain, official MAGICIAN coverage replayed bitwise (240/240);
  * coverage normalised by the evaluator-GT visibility ratio (uav_visibility_official.py; only the two v1 tiles change);
  * AUC@T = trapz(C[0..T]) / T, Cov@T = C[T], Final = C[100]; tile-equal means of 10-start means; paired tile bootstrap 10,000, seed 0.
Outputs fig/table_uav/: table_uav.{csv,tex,pdf,png}, table_uav_per_tile.{csv,tex}, table_uav_paired.csv (README.md is hand-written).
Usage: python make_table_uav.py   (seen2scene env, CPU)"""
import csv
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cvpr_lib as L  # noqa: E402
import render as RD  # noqa: E402

R = "/bsuscratch/jiahuizhang/projects/occupancy/seen2scene"
RES = os.path.join(R, "experiments", "cvpr_results", "exp7", "results")
OUT = os.path.join(L.FIG, "table_uav")
K = ["AUC@20", "AUC@50", "AUC@100", "Cov@20", "Cov@50", "Final"]
ORDER = ["Random Walk", "MAGICIAN", "Ours"]
TILE_NAME = {"uav_AMtown_11": "AMtown-11", "uav_AMtown_12": "AMtown-12", "uav_HKairport_00": "HKairport-00", "uav_HKairport_01": "HKairport-01",
             "uav_AMvalley_01_v1": "AMvalley-01†", "uav_HKisland_00_v1": "HKisland-00†"}


def main():
    S = json.load(open(os.path.join(RES, "uav_final_evalnorm_summary.json")))["UAV-final"]
    assert not S["invalid_or_missing"], S["invalid_or_missing"]
    rows = {r["method"]: r for r in S["rows"]}
    assert all(rows[m]["tiles"] == "6/6" for m in ORDER)
    os.makedirs(OUT, exist_ok=True)
    # main table
    body = [[m] + [f"{rows[m][k]:.3f}" for k in K] for m in ORDER]
    best = {(i, j + 1) for j, k in enumerate(K) for i, m in enumerate(ORDER) if rows[m][k] == max(rows[x][k] for x in ORDER)}
    hdr = ["Method"] + [k + " ↑" for k in K]
    L.write_csv(os.path.join(OUT, "table_uav.csv"), ["Method"] + K, body)
    p = S["pairs"]["Ours - MAGICIAN"]
    note = ("UAVScenes (zero-shot; 6 tiles x 10 starts, 100 steps; official MAGICIAN coverage, evaluator-GT visibility normalisation). "
            f"Ours - MAGICIAN: AUC@100 {p['AUC@100']['mean']:+.3f} [{p['AUC@100']['ci95'][0]:+.3f}, {p['AUC@100']['ci95'][1]:+.3f}], "
            f"Final {p['Final']['mean']:+.3f} [{p['Final']['ci95'][0]:+.3f}, {p['Final']['ci95'][1]:+.3f}]; higher on 6/6 tiles.")
    RD.table(os.path.join(OUT, "table_uav"), hdr, body, bold=best, notes=[note], rules_after=())
    cap = ("Zero-shot active mapping on UAVScenes (6 tiles from AMtown, AMvalley, HKairport, HKisland; 10 seeded starts per tile; 100 steps). "
           "Coverage is the official MAGICIAN coverage, normalised by the fraction of the evaluator's ground-truth points visible from the reachable "
           "camera poses; values are tile-equal means. No method was trained or tuned on UAVScenes. "
           f"Ours - MAGICIAN (paired tile bootstrap, 95% CI): AUC@100 {p['AUC@100']['mean']:+.3f} [{p['AUC@100']['ci95'][0]:+.3f}, {p['AUC@100']['ci95'][1]:+.3f}], "
           f"Final {p['Final']['mean']:+.3f} [{p['Final']['ci95'][0]:+.3f}, {p['Final']['ci95'][1]:+.3f}].")
    RD.tex(os.path.join(OUT, "table_uav.tex"), ["Method"] + [k + r" $\uparrow$" for k in K], body, bold=best, caption=cap, label="tab:uavscenes",
           notes=["generated by experiments/cvpr_results/scripts/make_table_uav.py -- do not edit by hand (needs booktabs)"])
    # per tile
    pt = list(csv.DictReader(open(os.path.join(RES, "uav_final_evalnorm_UAV-final_per_tile.csv"))))
    tiles = [t for t in TILE_NAME if any(r["tile"] == t for r in pt)]
    assert len(tiles) == 6
    prow = []
    for t in tiles:
        for m in ORDER:
            r = next(x for x in pt if x["tile"] == t and x["method"] == m)
            prow.append([TILE_NAME[t], m] + [f"{float(r[k]):.3f}" for k in K])
    L.write_csv(os.path.join(OUT, "table_uav_per_tile.csv"), ["Tile", "Method"] + K, prow)
    RD.tex(os.path.join(OUT, "table_uav_per_tile.tex"), ["Tile", "Method"] + K, prow, rules_after=set(range(2, len(prow) - 1, 3)),
           caption="UAVScenes per tile (10 starts each). † UAV-v1 tile: mesh holes sealed so that no reachable camera position lies under the reconstructed surface.",
           label="tab:uavscenes_tiles", colspec="ll" + "c" * len(K))
    # paired
    pr = []
    for name, v in S["pairs"].items():
        for k in K:
            pr.append([name, k, f"{v[k]['mean']:+.4f}", f"{v[k]['ci95'][0]:+.4f}", f"{v[k]['ci95'][1]:+.4f}", f"{v[k]['tiles_higher']}/6",
                       f"{v[k]['episodes_higher']}/{v[k]['episodes']}"])
    L.write_csv(os.path.join(OUT, "table_uav_paired.csv"), ["comparison", "metric", "mean", "ci95_lo", "ci95_hi", "tiles_higher", "episodes_higher"], pr)
    print(open(os.path.join(OUT, "table_uav.csv")).read())


if __name__ == "__main__":
    main()
