"""CVPR Table 2, paper layout v2 (CPU): MAGICIAN vs Ours on the splits of our model (Train-6 / Dev-5 / Test-3 / Dev+Test-8),
same six columns as Table 1 v2 (AUC up @20 / @50 / @100, Coverage up @20 / @50 / Final = @100), single-column width, the better of
the two rows bold within each split (after rounding to 3 decimals; ties both bold). No CI rows (user decision 2026-11-10); the paired
differences with scene-bootstrap CIs stay in table2_splits.csv. Values: scene-equal means over the split's scenes, each scene = mean of
its 5 official starts, read from manifest/episodes.csv. Output: fig/table2/table2_v2.{pdf,png,tex,csv}."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cvpr_lib as L  # noqa: E402
import render as RD  # noqa: E402

plt = RD.plt
OUT = os.path.join(L.FIG, "table2")
COLS = [("AUC", "@20", "AUC@20"), ("AUC", "@50", "AUC@50"), ("AUC", "@100", "AUC@100"), ("Coverage", "@20", "Cov@20"), ("Coverage", "@50", "Cov@50"), ("Coverage", "Final", "Final")]
SPLITS = [("Train-6", "Train (6)"), ("Dev-5", "Dev (5)"), ("Test-3", "Test (3)"), ("Dev+Test-8", "Dev+Test (8)")]
METH = [("MAG-B", "MAGICIAN"), ("V3-T0-D1", "Ours")]


def values():
    mets = [k for _, _, k in COLS]
    tab = {m: L.scene_table(L.load_manifest(m), mets) for m, _ in METH}
    for m, _ in METH:
        assert len(tab[m]) == 14, (m, len(tab[m]))
    return {(g, m): [L.group_mean(tab[m], L.GROUPS[g], k)[0] for k in mets] for g, _ in SPLITS for m, _ in METH}


def bold_cells(V):
    out = set()
    for g, _ in SPLITS:
        for j in range(len(COLS)):
            r = {m: round(V[(g, m)][j], 3) for m, _ in METH}
            out |= {(g, m, j) for m in r if r[m] == max(r.values())}
    return out


def draw(V, width=3.35, fs=7.6):
    B = bold_cells(V)
    rh = 0.158
    nrow = len(SPLITS) * len(METH)
    cw = [0.66, 0.62] + [(width - 0.66 - 0.62 - 0.05) / len(COLS)] * len(COLS)
    H = rh * (nrow + 2.4) + 0.05 * (len(SPLITS) - 1) + 0.55
    fig = plt.figure(figsize=(width, H))
    ax = fig.add_axes([0, 0, 1, 1]); ax.set_xlim(0, width); ax.set_ylim(0, H); ax.axis("off")
    x0 = [0.03 + sum(cw[:j]) for j in range(len(cw))]
    xc = [x0[j] + cw[j] / 2 for j in range(len(cw))]
    xr = x0[-1] + cw[-1]
    y = H - 0.06
    ax.plot([0.03, xr], [y, y], color="k", lw=0.9)
    y1 = y - rh * 0.62
    ax.text(x0[0] + 0.02, y1 - rh * 0.5, "Split", fontsize=fs, va="center", ha="left")
    ax.text(x0[1] + 0.02, y1 - rh * 0.5, "Method", fontsize=fs, va="center", ha="left")
    for grp, (a, b) in (("AUC $\\uparrow$", (2, 4)), ("Coverage $\\uparrow$", (5, 7))):
        ax.text((x0[a] + x0[b] + cw[b]) / 2, y1, grp, fontsize=fs, ha="center", va="center")
        ax.plot([x0[a] + 0.03, x0[b] + cw[b] - 0.03], [y1 - rh * 0.42] * 2, color="k", lw=0.45)
    y2 = y1 - rh * 0.95
    for j, (_, sub, _) in enumerate(COLS, 2):
        ax.text(xc[j], y2, sub, fontsize=fs, ha="center", va="center")
    y = y2 - rh * 0.55
    ax.plot([0.03, xr], [y, y], color="k", lw=0.5)
    y -= rh * 0.1
    for gi, (g, gl) in enumerate(SPLITS):
        if gi:
            y -= 0.025
            ax.plot([0.03, xr], [y, y], color="k", lw=0.3)
            y -= 0.025
        for mi, (m, ml) in enumerate(METH):
            yc = y - rh * 0.5
            y -= rh
            if mi == 0:
                ax.text(x0[0] + 0.02, yc - rh * 0.5, gl, fontsize=fs, va="center", ha="left")
            ax.text(x0[1] + 0.02, yc, ml, fontsize=fs, va="center", ha="left", fontweight="bold" if m == "V3-T0-D1" else "normal")
            for j, v in enumerate(V[(g, m)]):
                ax.text(xc[j + 2], yc, f"{v:.3f}", fontsize=fs, ha="center", va="center", fontweight="bold" if (g, m, j) in B else "normal")
    y -= rh * 0.1
    ax.plot([0.03, xr], [y, y], color="k", lw=0.9)
    notes = ["Scene-equal means (5 official starts per scene); Final = coverage after 100 steps; bold: better of the two.",
             "Our network was trained on Train scenes only (checkpoint selected on held-out Train trajectories); the planner",
             "variant was chosen on Dev; Test was used for neither. MAGICIAN's weights were trained on 8 of the 14 scenes",
             "(all Train scenes, 2 Dev scenes)."]
    for n in notes:
        y -= 0.125
        ax.text(0.03, y, n, fontsize=fs - 2.4, va="center", ha="left", color="#333333")
    return fig


def tex(V):
    B = bold_cells(V)
    T = [r"% Table 2 (paper layout v2), generated by experiments/cvpr_results/scripts/make_table2_v2.py -- do not edit by hand; needs \usepackage{booktabs,multirow}",
         r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{3pt}", r"\begin{tabular}{@{}llcccccc@{}}", r"\toprule",
         r" & & \multicolumn{3}{c}{AUC $\uparrow$} & \multicolumn{3}{c}{Coverage $\uparrow$} \\", r"\cmidrule(lr){3-5} \cmidrule(l){6-8}",
         r"Split & Method & @20 & @50 & @100 & @20 & @50 & Final \\", r"\midrule"]
    for gi, (g, gl) in enumerate(SPLITS):
        if gi:
            T.append(r"\midrule")
        for mi, (m, ml) in enumerate(METH):
            cells = [(r"\textbf{" + f"{v:.3f}" + "}") if (g, m, j) in B else f"{v:.3f}" for j, v in enumerate(V[(g, m)])]
            first = (r"\multirow{2}{*}{" + gl + "}") if mi == 0 else ""
            T.append(first + " & " + (r"\textbf{Ours}" if m == "V3-T0-D1" else ml) + " & " + " & ".join(cells) + r" \\")
    T += [r"\bottomrule", r"\end{tabular}",
          r"\caption{MAGICIAN vs.\ Ours on the scene splits of our model (scene-equal means over 5 official starts per scene; Final: coverage after 100 steps; bold: better of the two). "
          r"Our network was trained on the Train scenes only (checkpoint selected on held-out Train trajectories); the planner variant was chosen on Dev; Test was used for neither. "
          r"MAGICIAN's weights were trained on 8 of the 14 scenes (all Train scenes and 2 Dev scenes).}", r"\label{tab:splits}", r"\end{table}"]
    return "\n".join(T) + "\n"


if __name__ == "__main__":
    V = values()
    RD.save(draw(V), os.path.join(OUT, "table2_v2"))
    open(os.path.join(OUT, "table2_v2.tex"), "w").write(tex(V))
    L.write_csv(os.path.join(OUT, "table2_v2.csv"), ["split", "n_scenes", "method_id", "method"] + [k for _, _, k in COLS],
                [[g, len(L.GROUPS[g]), m, ml] + [repr(v) for v in V[(g, m)]] for g, _ in SPLITS for m, ml in METH])
    for g, gl in SPLITS:
        for m, ml in METH:
            print(f"{gl:13s} {ml:9s} " + " ".join(f"{v:.3f}" for v in V[(g, m)]))
