"""EXP8 -- tables and figures from the aggregated measurements (CPU, seen2scene env). Run after eff_analyze.py and eff_thresholds.py.
Table E1 (efficiency, identical states, 7 trajectories), Table E2 (RAYSCOUT component breakdown, profiled runs, 2 trajectories),
Table E3 (runtime scaling K x planner, 2 trajectories, with the Table 3 / Table 1 coverage), Table E4 (steps and cumulative planning
time to coverage thresholds), Figure E1 (stacked component bars, non-overlapping), Figure E2 (coverage vs decision latency).
Outputs: experiments/cvpr_results/efficiency/{tables,figures}/ (csv / md / tex / pdf / png)."""
import csv
import glob
import json
import os
import sys

import numpy as np

R = "/bsuscratch/jiahuizhang/projects/occupancy/seen2scene"
E = os.path.join(R, "experiments", "cvpr_results", "efficiency")
TAB, FIG, RAW = os.path.join(E, "tables"), os.path.join(E, "figures"), os.path.join(E, "raw")
sys.path.insert(0, os.path.join(R, "experiments", "cvpr_results", "scripts"))
import render as RD  # noqa: E402

plt = RD.plt
W = (10, 99)


def rows_of(method, src, scenes=None):
    out = []
    for p in glob.glob(os.path.join(RAW, f"{method}__{src}_*.jsonl")):
        sc = os.path.basename(p)[len(f"{method}__{src}_"):-len(".jsonl")]
        if scenes and sc not in scenes:
            continue
        out += [dict(json.loads(l), traj=sc) for l in open(p)]
    return out


def win(rows):
    return [r for r in rows if W[0] <= r["t"] <= W[1]]


def st(x):
    x = np.asarray([v for v in x if v is not None], float)
    return {"mean": float(x.mean()), "median": float(np.median(x)), "p95": float(np.percentile(x, 95)), "std": float(x.std(ddof=1)), "n": int(len(x))}


def write(name, header, rows):
    with open(os.path.join(TAB, name + ".csv"), "w", newline="") as f:
        w = csv.writer(f); w.writerow(header); w.writerows(rows)
    md = "| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n" + "".join("| " + " | ".join(str(c) for c in r) + " |\n" for r in rows)
    open(os.path.join(TAB, name + ".md"), "w").write(md)
    tex = ["% generated by experiments/cvpr_results/efficiency/scripts/eff_report.py", r"\begin{tabular}{@{}l" + "c" * (len(header) - 1) + "@{}}", r"\toprule",
           " & ".join(h.replace("%", r"\%").replace("_", r"\_") for h in header) + r" \\", r"\midrule"]
    tex += [" & ".join(str(c).replace("%", r"\%").replace("_", r"\_").replace("±", r"$\pm$").replace("×", r"$\times$") for c in r) + r" \\" for r in rows]
    tex += [r"\bottomrule", r"\end{tabular}"]
    open(os.path.join(TAB, name + ".tex"), "w").write("\n".join(tex) + "\n")


def main():
    os.makedirs(FIG, exist_ok=True)
    params = json.load(open(os.path.join(TAB, "model_params.json")))
    runs = list(csv.DictReader(open(os.path.join(TAB, "runs.csv"))))
    peak = lambda m, src: [float(r["peak_mem_gb"]) for r in runs if r["method"] == m and r["src"] == src]
    ours, mag = win(rows_of("OURS-K4D2", "V3-T0-D1")), win(rows_of("MAG-B", "V3-T0-D1"))
    prof = win(rows_of("OURS-K4D2-PROF", "V3-T0-D1"))
    two = {"redeemer_s0", "eiffel_s0"}
    # ---------------- Table E1
    so, sm = st([r["decision"] for r in ours]), st([r["decision"] for r in mag])
    co, cm = st([r["cycle"] for r in ours]), st([r["cycle"] for r in mag])
    pred_o = st([r["eff.gen_l1_s"] + r["eff.gen_l2_s"] for r in prof])
    plan_o = st([r["decision"] - r["eff.gen_l1_s"] - r["eff.gen_l2_s"] for r in prof])
    mag2 = [r for r in mag if r["traj"] in two]
    pred_m, plan_m = st([r["occupancy"] for r in mag2]), st([r["novelty"] + r["beam"] for r in mag2])
    sm2, so2 = st([r["decision"] for r in mag2]), st([r["decision"] for r in prof])
    po, pm = peak("OURS-K4D2", "V3-T0-D1"), peak("MAG-B", "V3-T0-D1")
    e1 = [["MAGICIAN beam (10×10)", f"{pred_m['mean']:.2f} / {plan_m['mean']:.2f} / {sm2['mean']:.2f}", f"{sm['mean']:.2f} ± {sm['std']:.2f}", f"{sm['median']:.2f}", f"{sm['p95']:.2f}", f"{cm['mean']:.2f}",
           f"{np.median(pm):.1f} ({min(pm):.1f}–{max(pm):.1f})", f"{params['MAGICIAN']['children']['scone'] / 1e6:.2f} M (+{params['MAGICIAN']['children']['depth'] / 1e6:.1f} M loaded)",
           f"{np.mean([r['evaluated_views'] for r in mag]):.0f}"],
          ["RAYSCOUT (K=4, CDGR)", f"{pred_o['mean']:.2f} / {plan_o['mean']:.2f} / {so2['mean']:.2f}", f"{so['mean']:.2f} ± {so['std']:.2f}", f"{so['median']:.2f}", f"{so['p95']:.2f}", f"{co['mean']:.2f}",
           f"{np.median(po):.1f} ({min(po):.1f}–{max(po):.1f})", f"{params['RAYSCOUT_V3-T0']['used_at_inference'] / 1e6:.2f} M",
           f"{np.mean([r['n_legal'] + (r['l2_predicted_views'] or 0) for r in ours]):.0f} (×K=4)"]]
    write("E1_efficiency", ["Method", "Prediction / planning / decision on the 2 profiled trajectories (s)†", "Decision mean ± std (s)", "Decision median (s)", "Decision P95 (s)", "Cycle incl. map update (s)",
                            "Peak GPU mem GB (median, range)", "Params", "Views evaluated / step"], e1)
    # ---------------- Table E2 (profiled runs; non-overlapping parts of the decision)
    mean = lambda k: float(np.mean([r[k] for r in prof]))
    parts = [("Planning geometry (P1 -> planner input)", mean("geometry")), ("GeoAnchor: refresh incl. 3D VAE encoder (amortised, every 10 steps)", mean("geoanchor_refresh")),
             ("RayForge L1: ray construction + projection features", mean("eff.gen_l1.projection_s_s")), ("RayForge L1: ray conditioning (latent sampling + 1D ray encoder)", mean("eff.gen_l1.cond_s_s")),
             ("RayForge L1: flow sampling (K=4, 10 Euler steps)", mean("eff.gen_l1.sampling_s_s")), ("RayForge L1: UNKNOWN-arc depth decoding + DistP1", mean("eff.gen_l1.decode_score_s_s")),
             ("CDGR L2: ray construction + projection features", mean("eff.gen_l2.projection_s_s")), ("CDGR L2: ray conditioning", mean("eff.gen_l2.cond_s_s")),
             ("CDGR L2: flow sampling (K=4, 10 Euler steps)", mean("eff.gen_l2.sampling_s_s")), ("CDGR L2: depth decoding + DistP1", mean("eff.gen_l2.decode_score_s_s")),
             ("CDGR: novel-surface test + weighted coverage (value_cov)", mean("eff.value_cov_s")),
             ("CDGR: expansion + path test + union + aggregation + choice", mean("decision") - sum(x for _, x in []) )]
    known = sum(v for _, v in parts[:-1])
    parts[-1] = (parts[-1][0], mean("decision") - known)
    tot = mean("decision")
    e2 = [[n, f"{v * 1000:.1f}", f"{100 * v / tot:.1f}%"] for n, v in parts] + [["Complete decision (sum)", f"{tot * 1000:.1f}", "100%"],
          ["  of which 3D VAE encoder per call (18 refreshes)", f"{float(np.mean([r['eff.vae_encode_s'] for r in prof if 'eff.vae_encode_s' in r])) * 1000:.1f}", "-"],
          ["  of which 1D ray encoder (all layers)", f"{mean('eff.ray_encoder_s') * 1000:.1f}", f"{100 * mean('eff.ray_encoder_s') / tot:.1f}%"],
          ["  of which depth decoding (all layers)", f"{mean('eff.depth_decode_s') * 1000:.1f}", f"{100 * mean('eff.depth_decode_s') / tot:.1f}%"],
          ["Online map update (not in the decision)", f"{mean('map_update') * 1000:.1f}", "-"],
          ["Candidates: first layer / second layer predicted views / search nodes", f"{mean('n_legal'):.1f} / {mean('l2_predicted_views'):.1f} / {mean('search_nodes'):.1f}", "-"]]
    write("E2_rayscout_breakdown", ["Component (per decision, t = 10..99, 2 trajectories)", "Mean (ms)", "Share of decision"], e2)
    # ---------------- Table E3 scaling (same 2 trajectories) + coverage of Table 3 / Table 1
    t3 = {r["method_id"]: r for r in csv.DictReader(open(os.path.join(R, "experiments", "cvpr_results", "fig", "table3", "table3_ablation.csv")))}
    t1 = {r["method_id"]: r for r in csv.DictReader(open(os.path.join(R, "experiments", "cvpr_results", "fig", "table1", "table1_all14_full.csv")))}
    cfg = [("R1", "OURS-K1D1", "V3-T0-K1D1", 1, "one-step coverage"), ("R2", "OURS-K4D1", "V3-T0-K4D1", 4, "one-step coverage"),
           ("R3", "OURS-K1D2", "V3-T0-K1D2", 1, "CDGR / D1"), ("R4", "OURS-K4D2", "V3-D1", 4, "CDGR / D1")]
    e3, pts = [], []
    for rid, m, tid, K, pl in cfg:
        rr = win(rows_of(m, "V3-T0-D1", two))
        s = st([r["decision"] for r in rr])
        cov = t3.get(tid) or t3.get("V3-T0-D1")
        e3.append([rid, K, 10, pl, f"{s['median']:.3f}", f"{s['mean']:.3f}", f"{s['p95']:.3f}", f"{np.mean([r['n_legal'] + (r.get('l2_predicted_views') or 0) for r in rr]):.1f}",
                   f"{float(cov['AUC@20']):.3f}", f"{float(cov['AUC@100']):.3f}", f"{float(cov['Final']):.3f}"])
        pts.append((rid + f" K={K}, {pl}", s["median"], float(cov["AUC@100"]), float(cov["AUC@20"])))
    e3.append(["MAGICIAN", "-", "-", "beam 10×10", f"{sm2['median']:.3f}", f"{sm2['mean']:.3f}", f"{sm2['p95']:.3f}", f"{np.mean([r['evaluated_views'] for r in mag2]):.0f}",
               f"{float(t1['MAG-B']['AUC@20']):.3f}", f"{float(t1['MAG-B']['AUC@100']):.3f}", f"{float(t1['MAG-B']['Final']):.3f}"])
    pts.append(("MAGICIAN beam", sm2["median"], float(t1["MAG-B"]["AUC@100"]), float(t1["MAG-B"]["AUC@20"])))
    write("E3_scaling", ["Config", "K", "Euler", "Planner", "Decision median (s)", "mean (s)", "P95 (s)", "Views / step", "AUC@20 (All-14)", "AUC@100 (All-14)", "Final (All-14)"], e3)
    # ---------------- Table E4 thresholds + cumulative planning time
    eps = list(csv.DictReader(open(os.path.join(TAB, "steps_to_threshold_episodes.csv"))))
    thr = ["0.5", "0.7", "0.8", "0.9"]
    med_lat = {"V3-T0-D1": so["median"], "MAG-B": sm["median"]}
    e4 = []
    for th in thr:
        for m, lab in (("V3-T0-D1", "RAYSCOUT"), ("MAG-B", "MAGICIAN")):
            v = [e[f"t@{th}"] for e in eps if e["method"] == m]
            reached = [int(x) for x in v if x not in ("", None)]
            sc = {}
            for e in eps:
                if e["method"] == m:
                    sc.setdefault(e["scene"], []).append(int(e[f"t@{th}"]) if e[f"t@{th}"] not in ("", None) else 101)
            meds = [float(np.median(x)) if sum(y <= 100 for y in x) >= 3 else None for x in sc.values()]
            mm = float(np.median([x if x is not None else 101 for x in meds]))
            e4.append([f"{int(float(th) * 100)}%", lab, f"{len(reached)}/{len(v)}", f"{mm:g}", f"{mm * med_lat[m]:.0f} (estimate)"])
    # exact cumulative planning time on replayed own trajectories
    exact = []
    for m, src, lab in (("OURS-K4D2", "V3-T0-D1", "RAYSCOUT"), ("MAG-B", "MAG-B", "MAGICIAN")):
        tid = "V3-T0-D1" if lab == "RAYSCOUT" else "MAG-B"
        for p in sorted(glob.glob(os.path.join(RAW, f"{m}__{src}_*.jsonl"))):
            sc = os.path.basename(p)[len(f"{m}__{src}_"):-len(".jsonl")]
            s, k = sc.rsplit("_s", 1)
            rr = sorted((json.loads(l) for l in open(p)), key=lambda r: r["t"])
            c = json.load(open(os.path.join(R, "work_dirs", "cvpr_results", "table1", "episodes", tid, f"{s}_s{k}.json")))["coverage_official"]
            for th in thr:
                idx = np.flatnonzero(np.asarray(c) >= float(th))
                if len(idx):
                    tt = int(idx[0])
                    exact.append([lab, sc, f"{int(float(th) * 100)}%", tt, f"{sum(r['decision'] for r in rr[:tt]):.1f}"])
                else:
                    exact.append([lab, sc, f"{int(float(th) * 100)}%", "not reached", "-"])
    write("E4_steps_to_threshold", ["Threshold", "Method", "Episodes reached", "Median of scene medians (steps)", "Steps × median decision latency (s)"], e4)
    write("E4b_cumulative_planning_time_exact", ["Method", "Trajectory (own, replayed)", "Threshold", "Steps", "Cumulative decision latency (s)"], exact)
    # ---------------- Figure E1: stacked components (RAYSCOUT profiled 2 traj; MAGICIAN same 2 traj)
    fig, ax = plt.subplots(figsize=(7.0, 1.9))
    groups = [("Geometry + GeoAnchor", parts[0][1] + parts[1][1], "#999999"), ("RayForge L1 (ray cond.)", parts[2][1] + parts[3][1], "#56B4E9"),
              ("RayForge L1 flow sampling", parts[4][1], "#0072B2"), ("RayForge L1 decode", parts[5][1], "#009E73"),
              ("CDGR L2 ray cond.", parts[6][1] + parts[7][1], "#CC79A7"), ("CDGR L2 flow sampling", parts[8][1], "#D55E00"), ("CDGR L2 decode", parts[9][1], "#E69F00"),
              ("CDGR coverage scoring", parts[10][1], "#F0E442"), ("CDGR search / other", parts[11][1], "#444444")]
    left = 0.0
    for n, v, ccol in groups:
        ax.barh(1, v, left=left, color=ccol, edgecolor="white", linewidth=0.8, label=n, height=0.55)
        left += v
    mg = [("MAGICIAN occupancy field", float(np.mean([r["occupancy"] for r in mag2])), "#BBBBBB"), ("MAGICIAN novelty", float(np.mean([r["novelty"] for r in mag2])), "#888888"),
          ("MAGICIAN beam search", float(np.mean([r["beam"] for r in mag2])), "#555555")]
    left = 0.0
    for n, v, ccol in mg:
        ax.barh(0, v, left=left, color=ccol, edgecolor="white", linewidth=0.8, label=n, height=0.55, hatch="//")
        left += v
    ax.set_yticks([0, 1]); ax.set_yticklabels(["MAGICIAN beam", "RAYSCOUT (K=4, CDGR)"])
    ax.set_xlabel("mean decision latency per step (s), NVIDIA L40S, identical states (redeemer, eiffel; t = 10..99)")
    ax.legend(ncol=4, fontsize=6.3, loc="upper center", bbox_to_anchor=(0.5, -0.38), frameon=False)
    RD.save(fig, os.path.join(FIG, "E1_runtime_breakdown"))
    # ---------------- Figure E2: coverage vs latency
    fig, axs = plt.subplots(1, 2, figsize=(7.4, 2.8))
    fig.subplots_adjust(wspace=0.42)
    for ax, j, lab in ((axs[0], 3, "AUC@20 (Macarons++ All-14)"), (axs[1], 2, "AUC@100 (Macarons++ All-14)")):
        for n, x, a100, a20 in pts:
            y = (a20, a100)[j == 2]
            mag_ = n.startswith("MAGICIAN")
            ax.scatter(x, y, s=40, marker="s" if mag_ else "o", color="#555555" if mag_ else ("#D55E00" if "R4" in n else "#E69F00"), zorder=3)
            ax.annotate(n.replace(" K=", "\nK=").replace("MAGICIAN beam", "MAGICIAN\nbeam 10x10"), (x, y), textcoords="offset points",
                        xytext=(-6, 4) if mag_ else (5, -3), ha="right" if mag_ else "left", fontsize=6.3)
        lo_, hi_ = ax.get_ylim(); ax.set_ylim(lo_ - 0.1 * (hi_ - lo_), hi_ + 0.12 * (hi_ - lo_))
        ax.set_xlim(0.2, 9.0)
        ax.set_xscale("log"); ax.set_xlabel("median decision latency per step (s, log)"); ax.set_ylabel(lab); ax.grid(alpha=0.25, lw=0.4)
    RD.save(fig, os.path.join(FIG, "E2_efficiency_coverage"))
    for name in ("E1_efficiency", "E2_rayscout_breakdown", "E3_scaling", "E4_steps_to_threshold", "E4b_cumulative_planning_time_exact"):
        print(open(os.path.join(TAB, name + ".md")).read())


if __name__ == "__main__":
    main()
