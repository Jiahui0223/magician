"""FisherRF-full (frozen variant f1c4) on MP3D-150 -- enqueue indoor episodes as tasks of the shared exclusive-GPU queue
(work_dirs/cvpr_results/gpu_queue, experiments/cvpr_results/scripts/gpu_queue_worker.sh: one task per GPU, taken in name order,
CUDA_VISIBLE_DEVICES set by the worker). One task = one episode: closed loop (fisherrf_full_sim_in.py, env FRF_FRONTIER_MODE=magician
FRF_REACH_FILTER=1, D12 docstring init) + validation (frf_in_validate.py: V1-V3 + EXP7 collect_mp3d150.validate, V4 same start as
EXP7 OURS, variant provenance, guard, RGB/zbuf).
Episodes: the 44 OURS rows of experiments/cvpr_results/exp7/manifests/mp3d150_manifest.csv (22 val levels x 2 starts), 150 moves.
Task names frf_in_f1c4_<NN>_<level>_S<start> (NN = rank by grid size, largest first, so the long episodes start first);
smoke: frf_in_0smoke_f1c4_<level>_S<start>.
Safety (as frf_queue_tasks.py): no task when validation.json is valid already or a task of the same episode is pending / running /
done (failed ones only with --retry-failed); in the task a mkdir claim full/jobs/qclaims_in_f1c4[_smoke]/<tag> prevents concurrent runs
of one episode (removed at task end; a hard-killed task leaves it: remove by hand). FisherRF is not bitwise reproducible (R1): a
partial episode is moved to full/_failed_in_f1c4/ and re-run from t = 0.
Usage: python frf_in_queue_tasks.py [--smoke] [--only TAG ...] [--moves N] [--retry-failed] [--dry-run]"""
import argparse
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
Q = os.path.join(REPO, "work_dirs", "cvpr_results", "gpu_queue")
FULL = os.path.join(REPO, "work_dirs", "cvpr_results", "fisherrf_reproduction", "full")
MANIFEST = os.path.join(REPO, "experiments", "cvpr_results", "exp7", "manifests", "mp3d150_manifest.csv")
MAG = "/bsuscratch/jiahuizhang/envs/magician/bin/python"
S2E = "/bsuscratch/jiahuizhang/envs/seen2scene/bin/python"

TEMPLATE = """#!/bin/bash
# FisherRF-full f1c4 indoor {tag} ({moves} moves): closed loop + validation (generated by frf_in_queue_tasks.py)
cd {repo}
OUT={root}; EPD=$OUT/FisherRF-full/{tag}; L={logs}; CL={claims}
mkdir -p $L {failed} $CL
if [ -f $EPD/validation.json ] && grep -q '"valid": true' $EPD/validation.json; then echo "validated already: $EPD"; exit 0; fi
mkdir $CL/{tag} 2>/dev/null || {{ echo "claimed by $(cat $CL/{tag}/owner 2>/dev/null)"; exit 4; }}
echo "${{WORKER_ID:-?}} $(hostname -s) gpu $CUDA_VISIBLE_DEVICES $(date '+%F %T')" > $CL/{tag}/owner
trap 'rm -rf $CL/{tag}' EXIT
echo "start $(date '+%F %T') host $(hostname -s) gpu $CUDA_VISIBLE_DEVICES variant f1c4 indoor"
if [ ! -f $EPD/episode.json ]; then
  [ -d $EPD ] && mv $EPD {failed}/{tag}_partial_$(date +%s)
  env -u LD_PRELOAD -u PYTHONPATH SLURM_JOB_QOS=kd-high FRF_FRONTIER_MODE=magician FRF_REACH_FILTER=1 {mag} \\
    {scripts}/fisherrf_full_sim_in.py --scan {scan} --level {level} --start {start} --moves {moves} --out $OUT \\
    > $L/{tag}.log 2>&1 || {{ echo "closed loop failed rc=$?"; tail -3 $L/{tag}.log; exit 1; }}
fi
env -u LD_PRELOAD -u PYTHONPATH {s2e} -B {scripts}/frf_in_validate.py --ep-dir $EPD --scene-id {scene_id} --start-id {start} --moves {moves} \\
  > $L/{tag}_val.log 2>&1 || {{ echo "validation failed rc=$?"; tail -2 $L/{tag}_val.log; exit 2; }}
tail -1 $L/{tag}_val.log; echo "end $(date '+%F %T')"
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true", help="root full/indoor/smoke_f1c4/, task prefix frf_in_0smoke_f1c4")
    ap.add_argument("--only", nargs="*", default=None, help="episode tags <level>_S<start>")
    ap.add_argument("--moves", type=int, default=150)
    ap.add_argument("--retry-failed", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    if not a.smoke:
        assert a.moves == 150, "full runs are 150 moves (MP3D-150)"
    rows = [r for r in csv.DictReader(open(MANIFEST)) if r["method"] == "OURS"]
    assert len(rows) == 44, len(rows)
    size = lambda r: eval(r["grid_n"].replace("x", "*"))                                            # noqa: E731
    rows.sort(key=lambda r: (-size(r), r["scene_id"], int(r["start_id"])))
    sfx = "_smoke" if a.smoke else ""
    root = os.path.join(FULL, "indoor", "smoke_f1c4" if a.smoke else "closed_loop_f1c4")
    existing = {d: set(os.listdir(os.path.join(Q, d))) if os.path.isdir(os.path.join(Q, d)) else set()
                for d in ("pending", "running", "done", "failed")}
    made, skipped = [], []
    for i, r in enumerate(rows):
        tag = f"{r['scene_id']}_S{r['start_id']}"
        if a.only is not None and tag not in a.only:
            continue
        name = f"frf_in_0smoke_f1c4_{tag}" if a.smoke else f"frf_in_f1c4_{i:02d}_{tag}"
        val = os.path.join(root, "FisherRF-full", tag, "validation.json")
        if os.path.exists(val) and '"valid": true' in open(val).read():
            skipped.append((name, "validated already"))
            continue
        hit = [d for d in ("pending", "running", "done") if any(x == f"{name}.sh" or x.startswith(f"{name}__") for x in existing[d])]
        if hit:
            skipped.append((name, f"task in {hit[0]}"))
            continue
        if not a.retry_failed and any(x.startswith(f"{name}__") for x in existing["failed"]):
            skipped.append((name, "task failed before (use --retry-failed)"))
            continue
        body = TEMPLATE.format(tag=tag, moves=a.moves, repo=REPO, root=root, scan=r["scan"], level=r["level"], start=r["start_id"],
                               scene_id=r["scene_id"], mag=MAG, s2e=S2E, scripts=HERE,
                               logs=os.path.join(FULL, "logs", f"queue_in_f1c4{sfx}"), failed=os.path.join(FULL, "_failed_in_f1c4"),
                               claims=os.path.join(FULL, "jobs", f"qclaims_in_f1c4{sfx}"))
        made.append(name)
        if not a.dry_run:
            tmp = os.path.join(Q, f".{name}.sh.tmp")
            with open(tmp, "w") as fh:
                fh.write(body)
            os.chmod(tmp, 0o755)
            os.replace(tmp, os.path.join(Q, "pending", f"{name}.sh"))      # atomic: a worker never sees a half-written task
    print(f"{'would enqueue' if a.dry_run else 'enqueued'} {len(made)}: {' '.join(made)}")
    for n, why in skipped:
        print(f"skip {n}: {why}")


if __name__ == "__main__":
    main()
