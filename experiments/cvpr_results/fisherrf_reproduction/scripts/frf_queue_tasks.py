"""FisherRF-full -- enqueue Macarons++ episodes as tasks of the shared exclusive-GPU queue
(work_dirs/cvpr_results/gpu_queue, experiments/cvpr_results/scripts/gpu_queue_worker.sh: one task per GPU, taken in name order,
CUDA_VISIBLE_DEVICES set by the worker). One task = one episode: closed loop (fisherrf_sim_out.py --planner fisherrf_full_planner.py,
D12 docstring init) + the official coverage replay (fisherrf_out_cov.py = Table 1 t25 procedure, must equal the stored curve).

Variants (pre-registered 2026-11-12):
  v4    FRF_FRONTIER_MODE=official  FRF_REACH_FILTER=1   root full/outdoor/closed_loop_v4/
  f1c4  FRF_FRONTIER_MODE=magician  FRF_REACH_FILTER=1   root full/outdoor/closed_loop_f1c4/
  (v3 = official without the filter, closed_loop_v3/, is frozen and never written here.)

Safety: a task is not created when its metrics already exist or a task of the same name is pending / running / done (failed tasks
are re-enqueued only with --retry-failed). Inside the task a mkdir claim (full/jobs/qclaims_<variant>/<scene>_s<k>) prevents two
concurrent runs of the same episode; it is removed when the task ends (a hard-killed task leaves it: remove it by hand). FisherRF
is not bitwise reproducible (R1), so a partial episode is never resumed: it is moved to full/_failed_<variant>/ and re-run from t = 0.
Usage: python frf_queue_tasks.py --variant v4|f1c4 --joblist FILE [--smoke] [--retry-failed] [--dry-run]
       joblist lines: <scene>:<start>[:<moves>]   (moves default 100)"""
import argparse
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
Q = os.path.join(REPO, "work_dirs", "cvpr_results", "gpu_queue")
FULL = os.path.join(REPO, "work_dirs", "cvpr_results", "fisherrf_reproduction", "full")
MAG = "/bsuscratch/jiahuizhang/envs/magician/bin/python"
VARIANTS = {"v4": {"FRF_FRONTIER_MODE": "official", "FRF_REACH_FILTER": "1"},
            "f1c4": {"FRF_FRONTIER_MODE": "magician", "FRF_REACH_FILTER": "1"}}

TEMPLATE = """#!/bin/bash
# FisherRF-full {variant} {u} ({moves} moves): closed loop + official coverage replay (generated by frf_queue_tasks.py)
cd {repo}
R={root}/{u}; EP=$R/episodes/ep_FisherRF_{u}_r0.json; MET=$R/metrics/FisherRF/FisherRF_{u}_r0.json; L={logs}
mkdir -p $L {failed} {claims}
[ -f $MET ] && {{ echo "metrics exist: $MET"; exit 0; }}
mkdir {claims}/{u} 2>/dev/null || {{ echo "claimed by $(cat {claims}/{u}/owner 2>/dev/null)"; exit 4; }}
echo "${{WORKER_ID:-?}} $(hostname -s) gpu $CUDA_VISIBLE_DEVICES $(date '+%F %T')" > {claims}/{u}/owner
trap 'rm -rf {claims}/{u}' EXIT
echo "start $(date '+%F %T') host $(hostname -s) gpu $CUDA_VISIBLE_DEVICES variant {variant}"
if [ ! -f $EP ]; then
  [ -d $R ] && mv $R {failed}/{u}_partial_$(date +%s)
  env -u LD_PRELOAD -u PYTHONPATH SLURM_JOB_QOS=kd-high FRF_FRONTIER_MODE={mode} FRF_REACH_FILTER={reach} {mag} \\
    {scripts}/fisherrf_sim_out.py --scene {scene} --start {start} --moves {moves} --root $R --init-pose docstring --verify-every 0 \\
    --planner fisherrf_full_planner.py > $L/{u}.log 2>&1 || {{ echo "closed loop failed rc=$?"; exit 1; }}
fi
env -u LD_PRELOAD -u PYTHONPATH {mag} {scripts}/fisherrf_out_cov.py --root $R --out $R/metrics --scene {scene} --start {start} \\
  > $L/{u}_cov.log 2>&1 || {{ echo "coverage replay failed rc=$?"; exit 2; }}
[ -f $MET ] || {{ echo "no metrics"; exit 3; }}
tail -1 $L/{u}_cov.log; echo "end $(date '+%F %T')"
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--variant", required=True, choices=list(VARIANTS))
    ap.add_argument("--joblist", required=True)
    ap.add_argument("--smoke", action="store_true", help="root full/outdoor/smoke_<variant>/, task prefix frf_0smoke_")
    ap.add_argument("--retry-failed", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    v = a.variant
    root = os.path.join(FULL, "outdoor", f"smoke_{v}" if a.smoke else f"closed_loop_{v}")
    prefix = f"frf_0smoke_{v}" if a.smoke else f"frf_{v}"
    existing = {d: set(os.listdir(os.path.join(Q, d))) if os.path.isdir(os.path.join(Q, d)) else set()
                for d in ("pending", "running", "done", "failed")}
    made, skipped = [], []
    for line in open(a.joblist):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        f = line.split(":")
        scene, start, moves = f[0], int(f[1]), int(f[2]) if len(f) > 2 else 100
        u = f"{scene}_s{start}"
        name = f"{prefix}_{u}"
        if os.path.exists(os.path.join(root, u, "metrics", "FisherRF", f"FisherRF_{u}_r0.json")):
            skipped.append((name, "metrics exist"))
            continue
        hit = [d for d in ("pending", "running", "done") if any(x == f"{name}.sh" or x.startswith(f"{name}__") for x in existing[d])]
        if hit:
            skipped.append((name, f"task in {hit[0]}"))
            continue
        if not a.retry_failed and any(x.startswith(f"{name}__") for x in existing["failed"]):
            skipped.append((name, "task failed before (use --retry-failed)"))
            continue
        body = TEMPLATE.format(variant=v, u=u, moves=moves, repo=REPO, root=root, scene=scene, start=start, mag=MAG,
                               scripts=HERE, logs=os.path.join(FULL, "logs", f"queue_{v}" + ("_smoke" if a.smoke else "")),
                               failed=os.path.join(FULL, f"_failed_{v}"), claims=os.path.join(FULL, "jobs", f"qclaims_{v}"),
                               mode=VARIANTS[v]["FRF_FRONTIER_MODE"], reach=VARIANTS[v]["FRF_REACH_FILTER"])
        made.append(name)
        if not a.dry_run:
            tmp = os.path.join(Q, f".{name}.sh.tmp")
            with open(tmp, "w") as fh:
                fh.write(body)
            os.chmod(tmp, 0o755)
            os.replace(tmp, os.path.join(Q, "pending", f"{name}.sh"))      # atomic: a worker never sees a half-written task
    print(f"{'would enqueue' if a.dry_run else 'enqueued'} {len(made)}: {' '.join(made)}")
    for n, why in skipped:
        print(f"skip {n}: {why}")


if __name__ == "__main__":
    main()
