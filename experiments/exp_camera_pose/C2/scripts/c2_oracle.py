"""Camera Pose C2 -- Stage A: one-step oracle gain of the C0 / C2a / C2b / C2c candidates on the MP3D VALSEL development
fixed states (magician env, 1 GPU; evaluation side: GT mesh of the 6 VALSEL houses only).

Identical to e2_pilot/scripts/e2_valsel_oracle.py for the replay and the gain (coverage replayed from the stored samples of
records 0..t; candidate frame rendered by the frozen MAGICIAN sensor at the candidate's (R, T); 10 % sample with the
trajectory's own seed derived_seed(key, start_pano, t + 1, "sample"); gain = |GT points newly within eps| / |GT points|),
with the candidate list generated by c2_poses.candidates(..., "ALL", ...) from the state's executed pose (GT used only by
the segment test = the motion constraint). Check: every C0 candidate's (R, T) and gain equal the stored legal list /
oracle.npz bitwise (STOP otherwise). Output work_dirs/exp_camera_pose/C2/oracle/<sid>.json (per candidate: fine pose, family,
legal costs, R, T, gain; executed history in fine units; generation counts).
Usage: python c2_oracle.py [--part i/n]"""
import argparse
import hashlib
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(HERE))))
EXP5 = os.path.join(REPO, "experiments", "exp5_future_view")
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(EXP5, "task2", "scripts"))
sys.path.insert(0, os.path.join(EXP5, "task1", "scripts"))
sys.path.insert(0, os.path.join(EXP5, "ablation_study", "common"))
sys.path.insert(0, os.path.join(EXP5, "task3_full_depth_p1", "e2_pilot", "scripts"))
import c2_poses as CP  # noqa: E402
import e2_paths as EP  # noqa: E402
import t2_common as C  # noqa: E402
import t21_traj as TJ  # noqa: E402
import t21_levels as LV  # noqa: E402

import numpy as np  # noqa: E402

S, T12, GE = TJ.S, TJ.T12, TJ.GE
OUT = os.path.join(REPO, "work_dirs", "exp_camera_pose", "C2", "oracle")


def main():
    import torch
    from scipy.spatial import cKDTree
    ap = argparse.ArgumentParser()
    ap.add_argument("--part", default="0/1")
    a = ap.parse_args()
    pi, pn = map(int, a.part.split("/"))
    dev = torch.device("cuda")
    man = json.load(open(os.path.join(EP.W, "valsel", "manifests", "states_valsel.json")))["states"]
    by_tag = {}
    for s in man:
        by_tag.setdefault(s["tag"], []).append(s)
    os.makedirs(OUT, exist_ok=True)
    for tag in sorted(by_tag)[pi::pn]:
        sts = {s["t"]: s for s in by_tag[tag]}
        if all(os.path.exists(os.path.join(OUT, f"{s['sid']}.json")) for s in sts.values()):
            continue
        tb = time.time()
        s0 = next(iter(sts.values()))
        key = s0["scene"]
        start_pano = int(s0["start"])
        td = os.path.join(EP.T2W, "mp3d", "traj", key, s0["traj"])
        C.assert_mesh_allowed(s0["scan"], "valsel")
        card = C.load_card(key)
        v, f = LV.mesh_zup(s0["scan"])
        sen = S.Sensor(S.zup_m_to_rt(v), f, dev)
        tree = cKDTree(TJ.gt_points(s0["scan"], card, v, f))
        eps = S.EPS_MODEL * card["k_I"]
        blk = T12.Blocker(v, f)
        g = GE.grid_def(card)
        covered = np.zeros(tree.n, bool)
        for t in range(max(sts) + 1):
            rec = np.load(os.path.join(td, "svc", f"svc_t{t}.npz"))
            covered |= TJ.near(tree, rec["sample_points"], eps)
            if t not in sts:
                continue
            st = sts[t]
            orc = np.load(os.path.join(EP.W, "valsel", "states", "indoor", st["sid"], "oracle.npz"))
            f0 = CP.to_fine(rec["pose_idx"])
            tq = time.time()
            legal, n_gen, n_oob, n_blk = CP.candidates(g, f0, "ALL", blk.blocked, S.rt_to_zup_m)
            t_gen = time.time() - tq
            seed = S.derived_seed(key, start_pano, t + 1, "sample")
            orig = {CP.to_fine(r): j for j, r in enumerate(rec["legal_idx"])}
            n_c0 = 0
            tq = time.time()
            for c in legal:
                e, az = CP.angles(g, c["f"])
                R, T = sen.RT(CP.position(g, c["f"]), e, az)
                fr = sen.render(R, T)
                pts = sen.sample(fr, seed)[0].cpu().numpy()
                c["gain"] = float((TJ.near(tree, pts, eps) & ~covered).sum()) / tree.n
                c["R"], c["T"] = R[0].cpu().numpy().astype(np.float64).tolist(), T[0].cpu().numpy().astype(np.float64).tolist()
                if c["family"] == "C0":
                    n_c0 += 1
                    j = orig.get(c["f"])
                    if j is None or not (np.array_equal(np.asarray(c["R"]), rec["legal_R"][j]) and np.array_equal(np.asarray(c["T"]), rec["legal_T"][j])) \
                            or c["gain"] != float(orc["gain"][j]):
                        raise SystemExit(f"STOP: C0 candidate {c['f']} differs from the stored legal list / oracle ({st['sid']}, j={j})")
            if n_c0 != len(rec["legal_idx"]):
                raise SystemExit(f"STOP: C0 family has {n_c0} legal candidates, stored list {len(rec['legal_idx'])} ({st['sid']})")
            t_ren = time.time() - tq
            hist = [list(CP.to_fine(r)) for r in rec["executed_pose_idx_history"]]
            out = {"sid": st["sid"], "tag": tag, "scene": key, "t": t, "f0": list(f0), "executed_history_fine": hist, "cov_t": float(covered.mean()),
                   "n_generated": n_gen, "n_out_of_bounds": n_oob, "n_blocked": n_blk, "n_legal": len(legal), "step_m": list(g["step_m"]),
                   "time_generate_s": t_gen, "time_render_gain_s": t_ren,
                   "candidates": [dict(c, f=list(c["f"])) for c in legal]}
            json.dump(out, open(os.path.join(OUT, f"{st['sid']}.json.tmp"), "w"))
            os.replace(os.path.join(OUT, f"{st['sid']}.json.tmp"), os.path.join(OUT, f"{st['sid']}.json"))
            best = max(legal, key=lambda c: c["gain"])
            print(tag, t, "legal", len(legal), "c0", n_c0, "blocked", n_blk, "oob", n_oob, "best %.4f (%s)" % (best["gain"], best["family"]),
                  "c0 best %.4f" % max(c["gain"] for c in legal if c["family"] == "C0"), flush=True)
        print(tag, "%.0fs" % (time.time() - tb), flush=True)
        torch.cuda.empty_cache()


if __name__ == "__main__":
    main()
